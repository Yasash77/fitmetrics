"""Downloadable PDF workout report (ReportLab)."""
from __future__ import annotations
import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INDIGO = colors.HexColor("#3D3BBF")
ORANGE = colors.HexColor("#FF7A2F")
MUTE = colors.HexColor("#6B6F8E")
LIGHT = colors.HexColor("#EEEDFD")


def _table(rows, widths):
    t = Table(rows, colWidths=widths)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), INDIGO), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 9.5),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7F7FD")]),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D5D7E6")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    return t


def workout_pdf(athlete: str, analysis: dict, zones: dict, strength: dict | None = None) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm, title="FitMetrics Workout Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=INDIGO, fontSize=22, alignment=0, spaceAfter=10)
    sub = ParagraphStyle("sub", parent=ss["Normal"], textColor=MUTE, fontSize=10)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=INDIGO, fontSize=13, spaceBefore=12, spaceAfter=6)
    body = ParagraphStyle("b", parent=ss["Normal"], fontSize=10.5, leading=15)
    box = ParagraphStyle("box", parent=body, backColor=colors.HexColor("#FFF4EC"), borderColor=ORANGE,
                         borderWidth=0, borderPadding=8, leftIndent=4, rightIndent=4)

    a = analysis
    story = [
        Paragraph("FitMetrics · Workout Report", h1),
        Paragraph(f"{athlete} &nbsp;·&nbsp; {datetime.now():%d %b %Y, %H:%M} &nbsp;·&nbsp; generated by FitMetrics API", sub),
        Spacer(1, 10), Paragraph(f"<b>Summary:</b> {a['summary']}", box), Spacer(1, 6),
        Paragraph("Session metrics", h2),
        _table([["Metric", "Value", "Metric", "Value"],
                ["Activity", a["activity"].replace("_", " ").title(), "Duration", f"{a['durationMin']:g} min"],
                ["Calories burned", f"{a['caloriesBurned']} kcal", "Calories / min", f"{a['caloriesPerMin']}"],
                ["Intensity", f"{a['percentHrr']}% HRR · {a['intensity']}", "Zone", a["zone"]],
                ["Training load", f"{a['trainingLoad']} TRIMP ({a['loadRating']})", "Recovery", f"~{a['recoveryHours']} h"],
                ["Fluids to drink", f"{a['hydration']['drinkLitres']} L", "Electrolytes",
                 "Yes" if a["hydration"]["electrolytes"] else "Not needed"]],
               [38 * mm, 50 * mm, 32 * mm, 54 * mm]),
        Paragraph("Heart-rate zones", h2),
        _table([["Zone", "Intensity", "BPM range"]] +
               [[z["zone"], z["intensity"], f"{z['min']}–{z['max']}"] for z in zones["zones"]],
               [70 * mm, 50 * mm, 54 * mm]),
        Paragraph(f"Max HR {zones['maxHr']} bpm (Tanaka) · Heart-rate reserve {zones['heartRateReserve']} bpm (Karvonen)", sub),
    ]
    if strength:
        s = strength
        rows = [["Metric", "Value"], ["Exercise", s["exercise"].replace("_", " ").title()],
                ["Estimated 1RM", f"{s['oneRepMax']} kg"],
                ["Strength load (85%)", f"{s['trainingLoads']['85%']} kg"],
                ["Hypertrophy load (70%)", f"{s['trainingLoads']['70%']} kg"]]
        if "strengthLevel" in s:
            rows += [["Relative strength", f"{s['relativeStrength']} × bodyweight"],
                     ["Strength level", s["strengthLevel"] + (f" (next: {s['nextLevel']} at {s['nextLevelAt']} kg)" if s.get("nextLevel") else "")]]
        story += [Paragraph("Strength analysis", h2), _table(rows, [70 * mm, 104 * mm])]
    story += [Spacer(1, 16), Paragraph("FitMetrics API · Yasash S (23MIC0060) · https://fitmetrics-api.onrender.com/docs", sub)]
    doc.build(story)
    return buf.getvalue()
