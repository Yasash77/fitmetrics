"""Downloadable 24-Formula Master Fitness Report PDF (ReportLab)."""
from __future__ import annotations
import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

EMERALD = colors.HexColor("#0F766E")
TEAL = colors.HexColor("#10B981")
MUTE = colors.HexColor("#64748B")
SOFT = colors.HexColor("#F0FDF4")


def _table(rows, widths):
    t = Table(rows, colWidths=widths)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), EMERALD),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5),
            ]
        )
    )
    return t


def fitness_sheet_pdf(report_data: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=14 * mm,
        bottomMargin=14 * mm,
        title="FitPulse 24-Formula Analytical Report Sheet",
    )
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=EMERALD, fontSize=20, alignment=0, spaceAfter=6)
    sub = ParagraphStyle("sub", parent=ss["Normal"], textColor=MUTE, fontSize=9.5)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=EMERALD, fontSize=12, spaceBefore=10, spaceAfter=5)
    body = ParagraphStyle("b", parent=ss["Normal"], fontSize=9.5, leading=14)
    box = ParagraphStyle(
        "box",
        parent=body,
        backColor=SOFT,
        borderColor=TEAL,
        borderWidth=0.5,
        borderPadding=7,
        leftIndent=4,
        rightIndent=4,
    )

    athlete = report_data.get("athlete", "Athlete")
    w = report_data["workout"]
    m = report_data["metabolic"]
    bc = report_data["bodyComposition"]

    story = [
        Paragraph("FitPulse · 24-Formula Analytical Report Sheet", h1),
        Paragraph(
            f"Athlete: <b>{athlete}</b> &nbsp;·&nbsp; {datetime.now():%d %b %Y, %H:%M} &nbsp;·&nbsp; FitPulse Intelligence Engine (23MIC0052)",
            sub,
        ),
        Spacer(1, 8),
        Paragraph(
            f"<b>Executive Summary:</b> {w['summary']} Daily maintenance (TDEE) is <b>{m['tdee']} kcal/day</b> "
            f"(Mifflin BMR {m['bmrMifflinStJeor']} kcal, Harris-Benedict {m['bmrHarrisBenedict']} kcal). "
            f"Body composition: BMI {bc['bmi']['bmi']} ({bc['bmi']['category']}), US Navy Body Fat {bc['bodyFat']['bodyFat']}%, "
            f"Fitness Age {bc['fitnessAge']} yrs.",
            box,
        ),
        Spacer(1, 6),
        Paragraph("Complete 24-Formula Analytical Matrix", h2),
    ]

    rows = [["#", "Domain", "Analytical Formula / Method", "Computed Result"]]
    for item in report_data["formulasSummary"]:
        rows.append([str(item["id"]), item["domain"], item["name"], str(item["value"])])

    story.append(_table(rows, [10 * mm, 30 * mm, 72 * mm, 66 * mm]))
    story.append(Spacer(1, 10))
    story.append(
        Paragraph(
            "Generated by FitPulse API (23MIC0052) · Partnered with FitMetrics API (23MIC0060)",
            sub,
        )
    )
    doc.build(story)
    return buf.getvalue()
