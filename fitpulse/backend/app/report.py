"""Downloadable FitPulse profile & progress report (ReportLab PDF)."""
from __future__ import annotations
import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

EMERALD = colors.HexColor("#0F766E")
TEAL = colors.HexColor("#10B981")
MUTE = colors.HexColor("#64748B")
SOFT = colors.HexColor("#F0FDF4")


def _table(rows, widths):
    t = Table(rows, colWidths=widths)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), EMERALD),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#CBD5E1")),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("TOPPADDING", (0, 0), (-1, -1), 4.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5),
            ]
        )
    )
    return t


def profile_pdf(r: dict) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
                            topMargin=16 * mm, bottomMargin=16 * mm, title="FitPulse Profile Report")
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], textColor=EMERALD, fontSize=22, alignment=0, spaceAfter=10)
    sub = ParagraphStyle("sub", parent=ss["Normal"], textColor=MUTE, fontSize=10)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=EMERALD, fontSize=13, spaceBefore=12, spaceAfter=6)
    e, b, iw = r["energy"], r["bmi"], r["idealWeight"]
    story = [Paragraph("FitPulse · Profile & Progress Report", h1),
             Paragraph(f"{r['athlete']} &nbsp;·&nbsp; {datetime.now():%d %b %Y} &nbsp;·&nbsp; generated by FitPulse API", sub),
             Paragraph("Energy needs", h2),
             _table([["Metric", "Value", "Metric", "Value"],
                     ["BMR (Mifflin-St Jeor)", f"{e['bmrMifflinStJeor']} kcal", "BMR (Harris-Benedict)", f"{e['bmrHarrisBenedict']} kcal"],
                     ["Activity level", f"{e['activityLevel']} (×{e['activityMultiplier']})", "Maintenance (TDEE)", f"{e['tdee']} kcal"],
                     ["Goal", e["goal"], "Target calories", f"{e['targetCalories']} kcal"],
                     ["Protein", f"{e['macros']['proteinGrams']} g", "Carbs / Fat", f"{e['macros']['carbsGrams']} g / {e['macros']['fatGrams']} g"]],
                    [40 * mm, 47 * mm, 40 * mm, 47 * mm]),
             Paragraph("Body composition", h2)]
    rows = [["Metric", "Value"], ["BMI", f"{b['bmi']} ({b['category']})"],
            ["Healthy weight range", f"{b['healthyWeightMinKg']} – {b['healthyWeightMaxKg']} kg"],
            ["Ideal weight (avg of 4 formulas)", f"{iw['idealWeightKg']} kg"]]
    if r.get("bodyFat"):
        bf = r["bodyFat"]
        rows += [["Body fat (US Navy)", f"{bf['bodyFat']} % ({bf['category']})"]]
        if "leanMass" in bf:
            rows += [["Lean / fat mass", f"{bf['leanMass']} kg / {bf['fatMass']} kg"]]
    story.append(_table(rows, [80 * mm, 94 * mm]))
    if r.get("goalPlan"):
        g = r["goalPlan"]
        story += [Paragraph("Goal plan", h2),
                  _table([["Metric", "Value"], ["Target", f"{g['currentWeight']} → {g['targetWeight']} kg in {g['weeks']:g} weeks"],
                          ["Weekly change", f"{g['weeklyChangeKg']} kg ({g['weeklyChangePctBodyweight']} % body weight)"],
                          ["Daily calorie target", f"{g['dailyCalorieTarget']} kcal"],
                          ["Safety", f"{g['safety']} — {g['advice']}"]], [50 * mm, 124 * mm])]
    prog = r.get("progress") or {}
    if prog.get("measurements"):
        story += [Paragraph("Recent measurements", h2),
                  _table([["Date", "Weight", "Waist", "Body fat"]] +
                         [[m["date"], f"{m['weight']} kg", f"{m['waist'] or '—'}", f"{m['bodyFat'] or '—'}"] for m in prog["measurements"]],
                         [44 * mm, 44 * mm, 43 * mm, 43 * mm])]
    if prog.get("workouts"):
        story += [Paragraph("Recent workouts (analysed by FitMetrics)", h2),
                  _table([["Date", "Activity", "Minutes", "kcal", "Zone", "Load"]] +
                         [[w["date"], w["activity"].replace("_", " "), f"{w['duration']:g}", f"{w['caloriesBurned']:g}",
                           (w["zone"] or "").split(" ·")[0], f"{w['trainingLoad']:g}"] for w in prog["workouts"]],
                         [28 * mm, 36 * mm, 22 * mm, 22 * mm, 40 * mm, 26 * mm])]
    story += [Spacer(1, 14), Paragraph("FitPulse API · Majit (23MIC0052) · workout data from partner FitMetrics (23MIC0060)", sub)]
    doc.build(story)
    return buf.getvalue()
